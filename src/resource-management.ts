import {reviseUnit,type Curriculum,type Resource,type Unit} from './curriculum';

export function removeResource(unit:Unit,id:string):Unit{
  return {...unit,resources:unit.resources.filter(resource=>resource.id!==id),stations:unit.stations.map(station=>({...station,sourceIds:station.sourceIds.filter(sourceId=>sourceId!==id)}))};
}
export function reorderResource(unit:Unit,id:string,direction:-1|1):Unit{
  const resources=[...unit.resources];
  const index=resources.findIndex(resource=>resource.id===id),other=index+direction;
  if(index<0||other<0||other>=resources.length)return unit;
  [resources[index],resources[other]]=[resources[other],resources[index]];
  return {...unit,resources};
}
export function assignResource(data:Curriculum,sourceId:string,targetId:string,resource:Resource,stations:number[]):Curriculum{
  const source=data.units.find(unit=>unit.id===sourceId),target=data.units.find(unit=>unit.id===targetId);
  if(!source||!target)throw new Error('المحطة المختارة غير موجودة.');
  if(sourceId!==targetId&&target.resources.some(item=>item.id===resource.id))throw new Error('هذا المصدر موجود بالفعل في المحطة المختارة. عدّل نسخته هناك أو اختر محطة أخرى.');
  return {...data,units:data.units.map(unit=>{
    if(unit.id===targetId){
      const exists=unit.resources.some(item=>item.id===resource.id);
      return reviseUnit({...unit,resources:exists?unit.resources.map(item=>item.id===resource.id?resource:item):[...unit.resources,resource],stations:unit.stations.map((station,index)=>({...station,sourceIds:[...station.sourceIds.filter(id=>id!==resource.id),...(stations.includes(index)?[resource.id]:[])]}))});
    }
    return unit.id===sourceId?reviseUnit(removeResource(unit,resource.id)):unit;
  })};
}

// Only files generated by uploadBookPdf belong to our managed storage lifecycle.
export function uploadedBookPath(url:string,publicBase:string):string|null{
  try{
    const candidate=new URL(url),base=new URL(publicBase);
    if(candidate.origin!==base.origin||candidate.username||candidate.password||!candidate.pathname.startsWith(base.pathname))return null;
    const path=decodeURIComponent(candidate.pathname.slice(base.pathname.length));
    return /^[0-9a-f-]{36}\.pdf$/i.test(path)?path:null;
  }catch{return null}
}
